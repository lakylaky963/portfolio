export function getStrings(lang) {
  return STRINGS[lang] || STRINGS.en;
}

export function t(lang, key, vars = {}) {
  const s = getStrings(lang);
  let v = s[key] ?? STRINGS.en[key] ?? key;
  if (typeof v === 'string') v = v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  return v;
}

